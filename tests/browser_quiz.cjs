const { chromium } = require(process.env.PLAYWRIGHT_MODULE || "playwright");
const assert = require("node:assert/strict");
const fs = require("node:fs/promises");
(async () => {
  const browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || "chrome", headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1050 }, acceptDownloads: true });
    const errors = [];
    page.on("pageerror", error => errors.push(error.message));
    await page.goto(process.env.BASE_URL || "http://127.0.0.1:8017");
    await page.locator('#login-form button[type="submit"]').click();
    await page.locator("#page-label").filter({ hasText: "43 matches" }).waitFor();
    await page.locator("#collection-filter").selectOption("1");
    await page.locator("#search").fill("harbor");
    for (const tag of ["approved", "campaign"]) {
      await page.locator("#include-tag-input").fill(tag);
      await page.locator("#include-tag-add").click();
    }
    await page.locator("#exclude-tag-input").fill("internal");
    await page.locator("#exclude-tag-add").click();
    await page.locator('#facet-media li[data-media="image"]').click();
    await page.locator("#page-label").filter({ hasText: "36 matches" }).waitFor();
    await page.locator("#btn-export:enabled").waitFor();
    assert.equal(await page.locator("#active-filters button").count(), 6);
    const first = await page.locator("#grid .card").evaluateAll(cards => cards.map(c => c.dataset.uuid));
    assert.equal(first.length, 24);
    await page.screenshot({ path: "docs/screenshots/07-quiz-search.png", fullPage: true });
    await page.locator("#page-next").click();
    await page.locator("#page-label").filter({ hasText: "Page 2 / 2" }).waitFor();
    await page.locator("#btn-export:enabled").waitFor();
    const second = await page.locator("#grid .card").evaluateAll(cards => cards.map(c => c.dataset.uuid));
    assert.equal(second.length, 12);
    assert.equal(new Set([...first, ...second]).size, 36);
    const downloadPromise = page.waitForEvent("download");
    await page.locator("#btn-export").click();
    const download = await downloadPromise;
    const data = await fs.readFile(await download.path());
    assert(data.subarray(0, 3).equals(Buffer.from([239, 187, 191])));
    for (const uuid of [...first, ...second]) assert(data.toString("utf8").includes(uuid));
    await page.locator("#sort").selectOption("oldest");
    await page.locator("#page-label").filter({ hasText: "Page 1 / 2" }).waitFor();
    await page.locator("#btn-export:enabled").waitFor();
    assert.equal(await page.locator("#grid .card .title").first().textContent(), "Harbor 00");
    await page.locator("#grid .card").first().click();
    await page.locator("#e-title").fill("Reviewed harbor 中文");
    await page.locator("#e-description").fill('Updated 中文, "quoted"\nsecond line');
    await page.locator("#d-save").click();
    await page.locator("#drawer-body .detail-title").filter({ hasText: "Reviewed harbor" }).waitFor();
    await page.locator("#grid .card .title").first().filter({ hasText: "Reviewed harbor" }).waitFor();
    await page.locator("#tag-add").fill("browser-check");
    await page.locator("#tag-add").press("Enter");
    await page.locator('#tag-row .rm[data-tag="browser-check"]').waitFor();
    await page.locator("#btn-export:enabled").waitFor();
    await page.locator("#drawer-close").click();
    const editedDownload = page.waitForEvent("download");
    await page.locator("#btn-export").click();
    const edited = await editedDownload;
    const editedData = await fs.readFile(await edited.path(), "utf8");
    assert(editedData.includes("Reviewed harbor 中文"));
    assert(editedData.includes("browser-check"));
    await page.locator("#grid .card").first().click();
    await page.locator('#tag-row .rm[data-tag="browser-check"]').click();
    await page.locator('#tag-row .rm[data-tag="browser-check"]').waitFor({ state: "detached" });
    await page.locator("#e-title").fill("Harbor 00");
    await page.locator("#e-description").fill('中文港口, "引号"\n第二行');
    await page.locator("#d-save").click();
    await page.locator("#drawer-body .detail-title").filter({ hasText: "Harbor 00" }).waitFor();
    await page.locator("#drawer-close").click();
    await page.locator("#clear-filters").click();
    await page.locator("#page-label").filter({ hasText: "43 matches" }).waitFor();
    assert.equal(await page.locator("#active-filters button").count(), 0);
    await page.locator("#search").fill("noresultsneedle");
    await page.locator("#page-label").filter({ hasText: "0 matches" }).waitFor();
    await page.locator("#btn-export:enabled").waitFor();
    const emptyDownload = page.waitForEvent("download");
    await page.locator("#btn-export").click();
    const empty = await emptyDownload;
    assert.equal((await fs.readFile(await empty.path(), "utf8")).trim().split(/\r?\n/).length, 1);
    await page.route("**/api/assets?**", route => route.abort());
    await page.locator("#search").fill("harbor");
    await page.locator("#search-status").filter({ hasText: "Could not load" }).waitFor();
    await page.unroute("**/api/assets?**");
    await page.locator("#search-retry").click();
    await page.locator("#btn-export:enabled").waitFor();
    assert.deepEqual(errors, []);
    console.log("Browser PASS: login, all filters, 36 matches, 2 stable pages, authenticated CSV download, sort/reset, edits, empty CSV, failed-query retry, clear, no JS errors");
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
